let dynamicTebakGambarData: TebakGambarItem[] = [...TEBAK_GAMBAR_LOCAL];

/**
 * Mengunduh database tebak gambar lengkap dari BochilTeam repository saat startup
 */
export async function initTebakGambarData(): Promise<void> {
  const url = 'https://raw.githubusercontent.com/BochilTeam/database/master/games/tebakgambar.json';
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(10000) });
    if (res.ok) {
      const data = await res.json() as any[];
      if (Array.isArray(data) && data.length > 0) {
        const valid = data.filter(item => item && item.img && item.jawaban);
        if (valid.length > 0) {
          dynamicTebakGambarData = valid;
          console.log(`🎮 [TebakGambar] Berhasil memuat ${dynamicTebakGambarData.length} soal tebak gambar dari BochilTeam.`);
          return;
        }
      }
    }
  } catch (err: any) {
    console.log(`ℹ️ [TebakGambar] Gagal memuat online, menggunakan ${TEBAK_GAMBAR_LOCAL.length} soal lokal: ${err?.message || err}`);
  }
}

/**
 * Mengambil satu soal tebak gambar secara acak
 */
export function getRandomTebakGambar(): TebakGambarItem {
  const list = dynamicTebakGambarData.length > 0 ? dynamicTebakGambarData : TEBAK_GAMBAR_LOCAL;
  const randomIndex = Math.floor(Math.random() * list.length);
  return list[randomIndex];
}

/**
 * Membuat petunjuk huruf tersamar (clue)
 * Contoh: "TANTANGAN SERU" -> "T _ N _ _ N G _ N   S _ R U"
 */
export function generateClue(answer: string, level = 1): string {
  const words = answer.toUpperCase().split(' ');
  return words
    .map(word => {
      const chars = word.split('');
      if (chars.length <= 3) return chars.join(' ');
      return chars
        .map((c, i) => {
          if (level === 1) {
            // Level 1: Tampilkan huruf pertama dan terakhir
            return i === 0 || i === chars.length - 1 ? c : '_';
          } else {
            // Level 2 (Bantuan Lebih Banyak): Tampilkan huruf genap
            return i % 2 === 0 || i === chars.length - 1 ? c : '_';
          }
        })
        .join(' ');
    })
    .join('    ');
}
